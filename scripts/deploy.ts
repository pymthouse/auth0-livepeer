#!/usr/bin/env node
import { randomBytes } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { optionalEnv, requireEnv } from "./lib/env.js";
import {
  defaultTenantYamlPath,
  provisionAuth0Deploy,
} from "./lib/provision.js";

async function main(): Promise<void> {
  const domain = requireEnv("AUTH0_DOMAIN");
  const mgmtClientId = requireEnv("AUTH0_MGMT_CLIENT_ID");
  const mgmtClientSecret = requireEnv("AUTH0_MGMT_CLIENT_SECRET");
  const appName = optionalEnv("APP_NAME", "Livepeer Platform");
  const apiAudience = optionalEnv("AUTH0_AUDIENCE", "livepeer");
  const tenantYamlPath = optionalEnv("AUTH0_TENANT_YAML", defaultTenantYamlPath());
  const outputPath = optionalEnv("BOOTSTRAP_OUTPUT", ".env.livepeer");
  const webhookSecret =
    process.env.WEBHOOK_SECRET?.trim() || randomBytes(24).toString("hex");

  console.log("[auth0-livepeer] deploying tenant.yaml to", domain);
  const auth0 = await provisionAuth0Deploy({
    domain,
    mgmtClientId,
    mgmtClientSecret,
    appName,
    apiAudience,
    tenantYamlPath,
  });

  console.log("[auth0-livepeer] public client:", auth0.publicClientId);
  console.log("[auth0-livepeer] m2m client:", auth0.m2mClientId);

  const envBlock = [
    "# Generated by auth0-livepeer deploy script",
    `AUTH0_DOMAIN=${domain}`,
    `AUTH0_ISSUER=${auth0.issuer}`,
    `AUTH0_JWKS_URL=${auth0.jwksUrl}`,
    `AUTH0_AUDIENCE=${auth0.apiIdentifier}`,
    `AUTH0_PUBLIC_CLIENT_ID=${auth0.publicClientId}`,
    `AUTH0_M2M_CLIENT_ID=${auth0.m2mClientId}`,
    `AUTH0_M2M_CLIENT_SECRET=${auth0.m2mClientSecret}`,
    "",
    `JWKS_URL=${auth0.jwksUrl}`,
    `JWT_ISSUER=${auth0.issuer}`,
    `JWT_AUDIENCE=${auth0.apiIdentifier}`,
    `WEBHOOK_SECRET=${webhookSecret}`,
    "CLAIM_CLIENT_ID=azp",
    "USAGE_SUBJECT_TYPE=auth0_user_id",
  ].join("\n");

  await writeFile(outputPath, `${envBlock}\n`, "utf8");
  console.log(`[auth0-livepeer] wrote ${outputPath}`);
}

main().catch((err) => {
  console.error("[auth0-livepeer] deploy failed:", err);
  process.exit(1);
});
